"""Assemble candidates/improved/autopicker_lc/bot.py (one standalone kit bot) from:
  v0_skeleton/bot.py  +  tournament plug-ins (hooks renamed to _cand_*)  +  layers_v1.py
Usage: python3 build.py [--shove balanced|minimal] [--out bot.py]"""
import argparse, ast, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PLUGINS = {  # file, hook name, new name, helper prefixes
    "shove": ("tournament/shove-defense/{}.py", "hook_facing_allin", "_cand_facing_allin", ("_sd_", "_SD_")),
    "preflop": ("tournament/preflop-structure/minimal.py", "hook_preflop", "_cand_preflop", ("_pf_", "_PF_")),
    "multiway": ("tournament/multiway-awareness/minimal.py", "hook_betting", "_cand_betting_mw", ("_mw_", "_MW_")),
}
DEFAULT_SETS = ["_SD_POST_BUDGET=0.0006", "_SD_POST_SAMPLES=48", "THINK_SECONDS=0.0003", "_MW_SECONDS=0.0004", "_MW_SAMPLES=32"]  # thinking-time budget (review #12)
DEFAULT_HOOKS = ("hook_facing_allin", "hook_preflop", "hook_betting", "hook_facing_bet", "hook_sizing")


def top_name(n):
    if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
        return n.name
    if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name):
        return n.targets[0].id
    return None


def extract(path, hook, new, prefixes):
    src = open(path, encoding="utf-8").read()
    out = []
    for n in ast.parse(src).body:
        nm = top_name(n)
        if nm and (nm == hook or nm.startswith(prefixes)):
            seg = ast.get_source_segment(src, n)
            if nm == hook:
                seg = seg.replace(f"def {hook}(", f"def {new}(", 1)
            out.append(seg)
    return f"\n\n# ---- plug-in from {os.path.relpath(path, ROOT).replace(os.sep, "/")} ----\n" + "\n\n\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shove", default="balanced")
    ap.add_argument("--out", default=os.path.join(HERE, "bot.py"))
    ap.add_argument("--no-baseline", dest="baseline", action="store_false", help="skip bot_baseline.py")
    ap.add_argument("--set", nargs="*", default=[], help="NAME=VALUE overrides for layer constants (ablations)")
    a = ap.parse_args()
    skel = open(os.path.join(ROOT, "v0_skeleton", "bot.py"), encoding="utf-8").read()
    tree = ast.parse(skel)
    # drop the default hook implementations
    for n in reversed(tree.body):
        if top_name(n) in DEFAULT_HOOKS:
            seg = ast.get_source_segment(skel, n)
            skel = skel.replace(seg + "\n", "", 1)
    blocks = ""
    for key, (rel, hook, new, pref) in PLUGINS.items():
        rel = rel.format(a.shove) if "{}" in rel else rel
        blocks += extract(os.path.join(ROOT, rel), hook, new, pref)
    layers = open(os.path.join(HERE, "layers_v1.py"), encoding="utf-8").read()

    marker = "EXTRA_TRACKERS = []\n"
    assert marker in skel
    skel = skel.replace(marker, marker + blocks + layers + "\n", 1)
    # Agent patches: tell trackers our seat; give trackers the final board before showdown
    skel = skel.replace('''        self.info = dict(info)''', '''        self.info = dict(info)
        for t in self.trackers.values():
            if hasattr(t, "me"):
                t.me = self.seat''', 1)
    skel = skel.replace('''            shown = summary.get("shown") or {}
            if shown:''', '''            if summary.get("board"):
                self._feed({"type": "board", "hand_id": hid, "street": "final", "board": list(summary["board"])})
            shown = summary.get("shown") or {}
            if shown:''', 1)
    for kv in DEFAULT_SETS + a.set:   # constant overrides (time budgets, ablation switches)
        name, val = kv.split("=", 1)
        skel, n = re.subn(rf"^{name} = .*$", f"{name} = {val}", skel, count=1, flags=re.M)
        assert n == 1, name
    header = ('"""autopicker-lc: lane C research bot (AlgoSoc kit format: Agent(), on_table_start, act, on_hand_end).\n'
              'Layers: 1 baseline (tournament plug-ins + v1 rules) -> 2 opponent profiles -> 3 personalities ->\n'
              '4 auto picker (in_character / deviating / changed / reactive) + out-of-character pool + safety nets.\n'
              f'GENERATED by candidates/improved/autopicker_lc/build.py (shove plug-in: {a.shove}). Edit the sources, not this file.\n"""\n')
    skel = re.sub(r'^""".*?"""\n', header, skel, count=1, flags=re.S)
    open(a.out, "w", encoding="utf-8", newline="\n").write(skel)
    compile(skel, a.out, "exec")
    print("wrote", a.out, len(skel), "bytes")
    if a.baseline and a.out == os.path.join(HERE, "bot.py"):
        base = re.sub(r"^_V1_USE_EXPLOIT = .*$", "_V1_USE_EXPLOIT = False", skel, count=1, flags=re.M)
        out = os.path.join(HERE, "bot_baseline.py")
        open(out, "w", encoding="utf-8", newline="\n").write(base)
        print("wrote", out, "(layers 2-4 off)")


if __name__ == "__main__":
    main()
