"""All-in preflop equity of every starting-hand class against every other.

    python3 tools/gen_matchups.py [trials]

Writes tools/matchups.py (MATCHUPS, decode, range_equity), pasted into bot.py.
"""
import base64
import os
import random
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import bot  # noqa: E402

CLASSES = bot.ORDER.split()
N = len(CLASSES)
TRIALS = int(sys.argv[1]) if len(sys.argv) > 1 else 2500


def combos(name):
    hi, lo = bot.RANKS.index(name[0]), bot.RANKS.index(name[1])
    if hi == lo:
        return [(hi * 4 + a, hi * 4 + b) for a in range(4) for b in range(a + 1, 4)]
    if name[2] == "s":
        return [(hi * 4 + s, lo * 4 + s) for s in range(4)]
    return [(hi * 4 + a, lo * 4 + b) for a in range(4) for b in range(4) if a != b]


COMBOS = [combos(c) for c in CLASSES]


def equity(pair):
    i, j = pair
    rng = random.Random(i * N + j)
    score, wins, n = bot.score, 0.0, 0
    for _ in range(TRIALS):
        a, b = rng.choice(COMBOS[i]), rng.choice(COMBOS[j])
        if set(a) & set(b):
            continue  # colliding draw is skipped; the rest stay uniform over legal deals
        rest = [c for c in range(52) if c not in a and c not in b]
        board = tuple(rng.sample(rest, 5))
        sa, sb = score(a + board), score(b + board)
        wins += 1.0 if sa > sb else 0.5 if sa == sb else 0.0
        n += 1
    return wins / n if n else 0.5


def main():
    pairs = [(i, j) for i in range(N) for j in range(i + 1, N)]
    with Pool() as pool:
        eq = pool.map(equity, pairs, chunksize=64)
    data = bytes(round(e * 255) for e in eq)
    text = base64.b85encode(data).decode()
    chunks = "\n".join(f'    "{text[k:k + 100]}"' for k in range(0, len(text), 100))
    with open(os.path.join(HERE, "matchups.py"), "w") as f:
        f.write(HEADER.replace("@@", chunks))


